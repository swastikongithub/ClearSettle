-- H2-compatible application schema for slice tests (the production schema is db/schema.sql, PostgreSQL).
create table if not exists app_user (
    id uuid primary key,
    iss varchar(500) not null,
    sub varchar(500) not null,
    email varchar(500),
    disabled boolean not null default false,
    created_at timestamp not null default current_timestamp,
    constraint app_user_iss_sub unique (iss, sub)
);
create table if not exists security_event (
    id bigint generated by default as identity primary key,
    at timestamp not null default current_timestamp,
    correlation_id varchar(100),
    event varchar(200) not null,
    app_user_id uuid,
    detail varchar(2000)
);
create table if not exists pending_action (
    id uuid primary key,
    user_id uuid not null,
    action_type varchar(200) not null,
    context varchar(2000),
    reviewed_version varchar(500),
    status varchar(20) not null,
    created_at timestamp with time zone not null default current_timestamp,
    executed_at timestamp with time zone
);
